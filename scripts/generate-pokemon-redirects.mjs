#!/usr/bin/env node
/* Writes public/_redirects: EN slug + DE name aliases → /:lang/pokemon/:id/
 * then the SPA fallback. Keep helper logic in sync with
 * src/lib/pokemon-slug-redirects.ts (covered by vitest). */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pokemon = JSON.parse(readFileSync(path.join(root, 'src/data/i18n/de/pokemon.json'), 'utf8'));

function slugifyDeName(name) {
  return name
    .toLowerCase()
    .replace(/ä/g, 'ae')
    .replace(/ö/g, 'oe')
    .replace(/ü/g, 'ue')
    .replace(/ß/g, 'ss')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

const LANGS = ['de', 'en'];
const lines = [
  '# Pokémon slug aliases → numeric canonical (trailing slash).',
  '# Generated by scripts/generate-pokemon-redirects.mjs — do not edit by hand.',
];
const seen = new Set();

for (const [id, row] of Object.entries(pokemon)) {
  const aliases = new Set();
  if (row.slug) aliases.add(row.slug);
  if (row.name) aliases.add(slugifyDeName(row.name));
  for (const alias of aliases) {
    if (!alias || alias === id) continue;
    for (const lang of LANGS) {
      const from = `/${lang}/pokemon/${alias}`;
      if (seen.has(from)) continue;
      seen.add(from);
      lines.push(`${from}  /${lang}/pokemon/${id}/  301`);
    }
  }
}

lines.push('');
lines.push('# Netlify SPA fallback — every other route serves index.html (client-side router)');
lines.push('/*    /index.html   200');
lines.push('');

writeFileSync(path.join(root, 'public/_redirects'), `${lines.join('\n')}\n`);
console.log(`[redirects] ${seen.size} pokemon slug rules → public/_redirects`);
